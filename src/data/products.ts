import type { ProductDefinition, ProductKind } from '../domain/catalog'

export const MAX_QUANTITY_OVERRIDES: Readonly<Record<string, number>> = Object.freeze({
  'private-train': 7_999,
  'private-island': 4_999,
})

export function defaultMaxQuantityPerRun(priceUsd: number): number {
  if (priceUsd <= 99) return 1_000_000_000
  if (priceUsd <= 9_999) return 10_000_000
  if (priceUsd <= 999_999) return 100_000
  if (priceUsd <= 99_999_999) return 10_000
  if (priceUsd <= 999_999_999) return 100
  if (priceUsd <= 9_999_999_999) return 10
  if (priceUsd <= 99_999_999_999) return 3
  return 1
}

interface ProductSource {
  readonly order: number
  readonly id: string
  readonly categoryId: string
  readonly nameZh: string
  readonly nameEn: string
  readonly priceUsd: number
  readonly kind: ProductKind
  readonly keywords: readonly string[]
}

function defineProduct(source: ProductSource): ProductDefinition {
  return Object.freeze({
    ...source,
    nameKey: `product.${source.id}`,
    maxQuantityPerRun:
      MAX_QUANTITY_OVERRIDES[source.id] ?? defaultMaxQuantityPerRun(source.priceUsd),
  })
}

